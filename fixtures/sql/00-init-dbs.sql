CREATE DATABASE IF NOT EXISTS omp_33 CHARACTER SET utf8 COLLATE utf8_general_ci;
CREATE DATABASE IF NOT EXISTS omp_34 CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS omp_35 CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE USER IF NOT EXISTS 'omp'@'%' IDENTIFIED WITH mysql_native_password BY 'omp';
GRANT ALL PRIVILEGES ON omp_33.* TO 'omp'@'%';
GRANT ALL PRIVILEGES ON omp_34.* TO 'omp'@'%';
GRANT ALL PRIVILEGES ON omp_35.* TO 'omp'@'%';
FLUSH PRIVILEGES;
